"""
Task 定义 — 连招可行性判定的 System / User prompt

单 Agent 任务：输入前一个动作和后一个动作，输出衔接可行性分析。
"""

from dataclasses import dataclass


@dataclass
class ComboInput:
    """连招判定输入"""
    moveA: str        # 前一个动作
    moveB: str        # 后一个动作

SYSTEM_COMBO = """你是武学世家出身的连招大师"连环手"，武林中论连招没有人比你更懂。

你从小就被师傅训练"一招接一招"的功夫——不是学单独的招式，而是练招与招之间的衔接。你深谙人体运动力学和实战节奏的奥秘。

你的分析基于真实的武术原理，不胡编乱造。你对每个维度的判断都会给出明确的理由。

你必须以 JSON 格式输出分析结果。"""


TASK_COMBO = """## 任务

分析从「前一个动作」到「后一个动作」的衔接可行性。

## 输入

### 前一个动作
{moveA}

### 后一个动作
{moveB}

## 分析维度

### 1. 前一个动作的结束态势

分析前一个动作完成后的身体状态：
- **重心位置**：前倾 / 后仰 / 居中 / 偏左 / 偏右 / 单脚（哪只脚）/ 腾空
- **发力状态**：发力已尽 / 余力未收 / 刚蓄满力 / 防御姿态
- **手脚位置**：双手和双脚大致在什么位置？是伸展还是回收？
- **身体朝向**：正面朝向 / 侧身 / 背对
- **门户状态**：是门户大开还是有防守姿态？

### 2. 后一个动作的起手要求

分析后一个动作对起手姿态的要求：
- **起手重心要求**：需要什么重心位置才能发出？
- **发力模式**：需要什么样的发力方式？爆发力 / 柔劲 / 惯性借力
- **需要手脚起始位置**：起手时手脚应该在什么位置？
- **距离要求**：这个动作需要在什么距离施展？

### 3. 衔接可行性核心分析

这是最核心的部分，综合判断两个动作之间的衔接：
- **身体力学匹配度** (0-100)：前动作的结束姿态是否适合直接转入后动作的起手？
  - 如果两个动作用到相同身体部位且发力方向一致 → 高
  - 如果需要大幅调整重心或换脚 → 低
  - 如果前动作结束后身体处于腾空状态 → 极低或需要落地缓冲
- **动量连续性** (0-100)：前动作的动量是否能自然延续到后动作？
  - 顺势衔接（如右拳回收带动左拳打出）→ 高
  - 逆势衔接（如猛向前冲后立刻后撤步）→ 低
- **节奏流畅度** (0-100)：整体动作是否流畅自然？
- **实战合理性** (0-100)：这个连招在实战中是否有意义？
  - 前打空后是否容易被反击？
  - 连招过程中是否有明显的破绽窗口？

### 4. 最终可行性评分

综合以上所有维度，给出一个最终的可行性概率值 (0.0-1.0)：

- **0.0-0.2**：几乎不可行。前动作的结束姿态完全不适合接后动作。
  需要明显的停顿或调整才能衔接，在实战中等于给对手送破绽。
  示例：腾空飞踢后接扫堂腿（还没落地）
- **0.2-0.4**：可行性低。需要明显调整才能衔接，实战中风险高。
  示例：全力前冲拳后接后撤步高踢（动量完全相反）
- **0.4-0.6**：中等可行。可以衔接，但中间有微小的卡顿或需要刻意调整。
  实战中可用但容易被有经验的对手利用间隙。
  示例：弓步冲拳后接转身鞭拳（需要转体调整）
- **0.6-0.8**：可行性高。两个动作衔接自然，在实战中可以流畅打出。
  示例：左右摆拳连击（利用左摆的回收力打出右摆）
- **0.8-1.0**：完美衔接。两个动作浑然天成，中间没有任何卡顿。
  属于精心设计的连招组合，实战中极难防御。
  示例：咏春日字冲拳连环（连续的同一动作）
  示例：太极拳的「云手」接「高探马」（套路中本就连续）

### 5. 衔接难度评级

- **入门**：基本同类型动作重复，任何练过的武者都可以做到
- **进阶**：需要一定的训练才能流畅衔接
- **高手**：需要有深厚功底才能做到不露破绽
- **绝技**：极为困难，只有顶级高手才能在实战中使用

### 6. 关键限制因素

最关键的限制是什么？简要说明。

### 7. 改进建议

如果可行性不高，有什么改进建议？如果用另一招替代后一个动作，什么招式会更合适？

## 输出格式（严格的 JSON）

```json
{{
  "moveA_end_state": {{
    "center_of_gravity": "前动作结束时的重心位置",
    "power_state": "发力状态",
    "limb_position": "手脚位置",
    "body_facing": "身体朝向",
    "guard_state": "门户状态"
  }},
  "moveB_requirements": {{
    "center_of_gravity_required": "后动作对重心的要求",
    "power_mode": "发力模式",
    "limb_start_position": "手脚起始位置要求",
    "distance_requirement": "距离要求"
  }},
  "feasibility_analysis": {{
    "body_mechanics_match": {{
      "score": 0,
      "reason": "身体力学匹配度的理由"
    }},
    "momentum_continuity": {{
      "score": 0,
      "reason": "动量连续性的理由"
    }},
    "rhythm_fluency": {{
      "score": 0,
      "reason": "节奏流畅度的理由"
    }},
    "combat_practicality": {{
      "score": 0,
      "reason": "实战合理性的理由"
    }}
  }},
  "feasibility": 0.0,
  "difficulty": "入门/进阶/高手/绝技",
  "key_limitation": "最关键的限制因素",
  "improvement_suggestion": "改进建议或替代招式"
}}
```
"""


def build_combo_prompt(inp: ComboInput) -> tuple[str, str]:
    """构建连招判定任务的 system 和 user prompt"""
    user = TASK_COMBO.format(
        moveA=inp.moveA,
        moveB=inp.moveB,
    )
    return SYSTEM_COMBO, user
